"""The project brief, .research/context/BRIEF.md: one page any session can read for the big picture — the dashboard's
own runs, the researcher's terminal sessions and Codex Desktop in the same folder alike.

Built from the project config, the panel sessions and dag.service.brief_data(pid) (stage, lens counts, what needs
revising or rerunning and why, confirmed facts, live attempts with their verdicts, open proposals, gates). Without a
research DAG (or before the DAG package exists) the brief still carries the project, the agents and where things live.

When it is regenerated (the simple, robust option):
  - on GET /api/projects/{pid}/brief,
  - before every non-ephemeral run (api.spec_for calls flush(): it regenerates at once when a change is pending or
    the file is missing, so an agent never reads a brief older than the DAG it is about to work on),
  - DEBOUNCE_S after a "dag" or "project" event (hooks.on_topic; a timer thread), so the user's own sessions see
    fresh content too.
The file is rewritten only when its content changed (the timestamp line aside), so it does not churn in git.
"""
from __future__ import annotations

import logging
import re
import threading
from typing import Any

from ..events import hub
from ..projects import project_config, project_root
from ..util import now_iso, write_text_atomic
from . import context, hooks, sessions

log = logging.getLogger("research_deck.agents")

DEBOUNCE_S = 5.0
TOP_ITEMS = 8
STAMP_PREFIX = "_Generated by Research Deck · "
_STAMP_RE = re.compile(r"^_Generated by Research Deck · (\S+)", re.M)
PROVIDER_LABELS = {"claude": "Claude Code", "codex": "Codex", "fake": "Fake agent"}

_timers: dict[str, threading.Timer] = {}
_timers_lock = threading.Lock()
_gen_lock = threading.Lock()


# ------------------------------------------------------------------ data

def dag_data(pid: str) -> dict | None:
    """dag.service.brief_data(pid), or None when the DAG package is absent or fails (the brief degrades)."""
    try:
        from ..dag import service  # lazy: the DAG slice may not be installed
    except Exception:  # noqa: BLE001
        return None
    try:
        data = service.brief_data(pid)
        return data if isinstance(data, dict) else None
    except Exception:  # noqa: BLE001
        log.exception("dag.service.brief_data failed for %s", pid)
        return None


def _title(value: Any) -> str:
    if isinstance(value, dict):
        en, zh = value.get("en"), value.get("zh")
        if en and zh and en != zh:
            return f"{en} ({zh})"
        return en or zh or ""
    return str(value) if value else ""


def _reason(value: Any) -> str:
    if isinstance(value, list):
        return "; ".join(filter(None, (_reason(v) for v in value[:3])))
    if isinstance(value, dict):
        if value.get("note"):
            return str(value["note"])
        addr = value.get("addr") or value.get("edge") or ""
        if value.get("from") or value.get("to"):
            return f"{addr} {value.get('from') or '∅'} → {value.get('to') or '∅'}".strip()
        return str(addr or value.get("level") or "")
    return str(value) if value else ""


def _count(value: Any) -> int | str:
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (int, float)):
        return int(value)
    if isinstance(value, dict):
        for k in ("count", "n", "total"):
            if isinstance(value.get(k), (int, float)):
                return int(value[k])
        if isinstance(value.get("ids"), list):
            return len(value["ids"])
        if isinstance(value.get("items"), list):
            return len(value["items"])
    if isinstance(value, list):
        return len(value)
    return "?"


def _item_line(d: Any) -> str:
    """One bullet for a DAG item of any of brief_data's shapes ({id|node, title, level, reason|why, cells, ...})."""
    if not isinstance(d, dict):
        return f"- {d}"
    ident = d.get("id") or d.get("node") or ""
    head = f"`{ident}`" if ident else ""
    if d.get("kind"):
        head += f" ({d['kind']})"
    text = _title(d.get("text") or d.get("statement"))
    title = _title(d.get("title")) or text
    if title:
        head = f"{head} {title}".strip()
    cells = d.get("cells") or ([d["cell"]] if d.get("cell") else [])
    if cells:
        shown = ", ".join(str(c) for c in cells[:4]) + (f" (+{len(cells) - 4})" if len(cells) > 4 else "")
        head += f" [{shown}]"
    tail = []
    if d.get("level"):
        tail.append(str(d["level"]))
    why = _reason(d.get("reason") or d.get("why") or d.get("reasons") or d.get("note"))
    if why:
        tail.append(why)
    if text and text != title:
        tail.append(text if len(text) <= 240 else text[:239] + "…")
    if d.get("est_gpu_h") is not None:
        tail.append(f"~{d['est_gpu_h']} GPU-h")
    return f"- {head}" + (f" — {': '.join(tail)}" if tail else "")


def _attempt_line(a: Any) -> str:
    if not isinstance(a, dict):
        return f"- {a}"
    group = a.get("alt_group") or a.get("group") or "?"
    tried = _count(a.get("tried")) if a.get("tried") is not None else "?"
    chosen = a.get("chosen")
    parts = [f"- `{group}`: {tried} tried", f"chosen `{chosen}`" if chosen else "none chosen yet"]
    dead = a.get("dead") or []
    if dead:
        verdicts = []
        for d in dead[:6]:
            if isinstance(d, dict):
                why = _reason(d.get("reason"))
                verdicts.append(f"`{d.get('id')}` {d.get('status', 'dead')}" + (f" ({why})" if why else ""))
            else:
                verdicts.append(str(d))
        parts.append("ruled out: " + "; ".join(verdicts))
    live = a.get("live") or a.get("active") or []
    if live:
        parts.append("still open: " + ", ".join(f"`{x.get('id') if isinstance(x, dict) else x}`" for x in live[:6]))
    return ", ".join(parts)


def _proposal_line(p: Any) -> str:
    if not isinstance(p, dict):
        return f"- {p}"
    ops = p.get("ops")
    n = len(ops) if isinstance(ops, list) else p.get("n_ops")
    who = p.get("by") or p.get("proposer")
    return (f"- `{p.get('id', '?')}` {_title(p.get('title'))}" + (f" ({n} ops)" if n else "")
            + (f", by {who}" if who else "") + (f" — {p['state']}" if p.get("state") else ""))


def _gate_line(g: Any) -> str:
    if not isinstance(g, dict):
        return f"- {g}"
    name = g.get("gate") or g.get("id") or "?"
    label = _title(g.get("label") or g.get("title"))
    state = g.get("status") or g.get("state") or ("passed" if g.get("passed") else "open")
    checks = g.get("checks")
    extra = ""
    if isinstance(checks, list) and checks:
        ok = sum(1 for c in checks if isinstance(c, dict) and (c.get("ok") or c.get("passed")))
        extra = f", {ok}/{len(checks)} checks green"
    return f"- {name}" + (f" {label}" if label else "") + f": {state}{extra}"


# ------------------------------------------------------------------ markdown

def _empty(data: dict) -> bool:
    """brief_data of a project without DAG nodes (the service returns empty results rather than failing)."""
    lenses = data.get("lenses") or {}
    if any(isinstance(_count(v), int) and _count(v) for v in lenses.values()):
        return False
    return not any(data.get(k) for k in ("revise", "rerun", "confirmed", "attempts", "open_proposals"))


def _agents_section(pid: str) -> list[str]:
    doc = sessions.load(pid)
    lines = []
    for panel in sessions.PANELS:
        entry = doc["panels"][panel]
        prov = entry["active"]
        s = entry[prov]
        sid = (s.get("session_id") or "")[:8]
        bits = [s.get("model"), s.get("effort")] + (["fast"] if s.get("fast") else [])
        lines.append(f"- {panel}: {PROVIDER_LABELS.get(prov, prov)} ({', '.join(b for b in bits if b)}), "
                     f"{'may edit files' if s.get('permission') == 'write' else 'read-only'}"
                     + (f", session `{sid}`" if sid else ", no session yet"))
    return lines


def build_markdown(pid: str) -> str:
    """The brief without its timestamp line."""
    cfg = project_config(pid)
    data = dag_data(pid)
    out = [f"# Project brief: {cfg.get('name')}", ""]
    facts = [f"stage **{cfg.get('stage')}**"]
    if data and data.get("stage"):
        facts.append(f"DAG stage {data['stage'] if not isinstance(data['stage'], dict) else _title(data['stage'])}")
    if cfg.get("venue"):
        facts.append(f"venue {cfg['venue']}")
    if cfg.get("deadline"):
        facts.append(f"deadline {cfg['deadline']}")
    out += ["Project " + ", ".join(facts) + ".", ""]
    if cfg.get("summary"):
        out += [str(cfg["summary"]).strip(), ""]

    if data is None or _empty(data):
        out += ["## Research DAG", "", "No research DAG yet (or the DAG service is unavailable). Stage, findings and "
                "open questions appear here once nodes exist in `.research/dag/`.", ""]
    else:
        lenses = data.get("lenses") or {}
        out += ["## At a glance", "",
                "- Lenses: " + " · ".join(f"{name} {_count(lenses.get(name, 0))}" for name in ("tried", "confirmed", "revise", "rerun")),
                ""]
        sections = [
            ("Needs revision (review, orphaned, broken)", data.get("revise"), _item_line),
            ("Needs a rerun", data.get("rerun"), _item_line),
            ("Confirmed facts", data.get("confirmed"), _item_line),
            ("Live attempts", data.get("attempts"), _attempt_line),
            ("Open proposals (waiting for the researcher)", data.get("open_proposals"), _proposal_line),
            ("Gates", data.get("gates"), _gate_line),
        ]
        for heading, items, fmt in sections:
            items = items or []
            if not items:
                continue
            out += [f"## {heading}", "", *(fmt(i) for i in items[:TOP_ITEMS])]
            if len(items) > TOP_ITEMS:
                out.append(f"- … {len(items) - TOP_ITEMS} more (rd_graph / the DAG view)")
            out.append("")

    out += ["## Agents on this project", "", *_agents_section(pid), ""]
    paper, code = cfg.get("paper") or {}, cfg.get("code") or {}
    out += [
        "## Where things live", "",
        f"- Paper: `{paper.get('main', '')}` (folder `{paper.get('dir', '')}`)",
        f"- Code roots: {', '.join(f'`{r}`' for r in code.get('roots') or []) or '—'}",
        f"- Figures: `{(cfg.get('figures') or {}).get('dir', '')}` (registry `.research/figures.json`)",
        f"- Experiments: `{(cfg.get('experiments') or {}).get('dir', '')}` (records `.research/experiments/`)",
        "- Research DAG: `.research/dag/` (nodes, runs, proposals, log); change it through the research-deck MCP tools",
        "- Handoff notes between Claude Code and Codex: `.research/context/handoffs/`",
        "- Dashboard transcripts per panel: `.research/context/transcripts/`",
        "- Session bindings: `.research/sessions.json`", "",
        "## Working with the DAG", "",
        "- Four lenses: **tried** (every attempt, dead ones included), **confirmed** (confirmed or locked and fresh), "
        "**revise** (live nodes in review, orphaned or broken), **rerun** (stale or unbuilt experiment cells).",
        "- Read with `rd_lenses`, `rd_graph`, `rd_node`, `rd_explain`; preview with `rd_impact` before `rd_apply`.",
        "- Edits to confirmed or locked nodes become proposals for the researcher; locking, approving and passing "
        "gates are the researcher's.",
        "",
    ]
    return "\n".join(out)


def _stamp(ts: str) -> str:
    return (f"{STAMP_PREFIX}{ts} · from the project config, the panel sessions and the research DAG. "
            "Do not edit: it is rewritten when the DAG changes._")


def _comparable(body: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", body.strip())


def _split(text: str) -> tuple[str | None, str]:
    """(generated_at, body without the stamp line)."""
    m = _STAMP_RE.search(text)
    body = "\n".join(line for line in text.splitlines() if not line.startswith(STAMP_PREFIX))
    return (m.group(1) if m else None), _comparable(body)


def generate(pid: str) -> dict:
    """Regenerate BRIEF.md (written only when the content changed). Returns {markdown, generated_at, changed}."""
    with _gen_lock:
        body = build_markdown(pid)
        path = context.brief_path(pid)
        try:
            old_ts, old_body = _split(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            old_ts, old_body = None, None
        if old_ts and old_body is not None and old_body == _comparable(body):
            return {"markdown": path.read_text(encoding="utf-8"), "generated_at": old_ts, "changed": False}
        ts = now_iso()
        lines = body.splitlines()
        text = "\n".join(lines[:1] + ["", _stamp(ts)] + lines[1:]) + "\n"
        write_text_atomic(path, text)
    hub.publish(pid, "file", {"path": ".research/context/BRIEF.md"})
    return {"markdown": text, "generated_at": ts, "changed": True}


# ------------------------------------------------------------------ keeping it fresh

def _job(pid: str, root: str) -> None:
    with _timers_lock:
        _timers.pop(pid, None)
    try:
        if str(project_root(pid)) != root:      # the registry changed meanwhile (another project now has this id)
            return
        generate(pid)
    except Exception:  # noqa: BLE001 — a background refresh must never surface
        log.debug("brief refresh for %s skipped", pid, exc_info=True)


def schedule(pid: str, delay: float = DEBOUNCE_S) -> None:
    """Regenerate after `delay` seconds of quiet (each call restarts the wait)."""
    try:
        root = str(project_root(pid))
    except Exception:  # noqa: BLE001 — unknown project
        return
    with _timers_lock:
        old = _timers.pop(pid, None)
        if old:
            old.cancel()
        timer = threading.Timer(delay, _job, args=(pid, root))
        timer.daemon = True
        timer.name = f"brief-{pid}"
        _timers[pid] = timer
        timer.start()


def flush(pid: str) -> None:
    """Make sure BRIEF.md is current right now: run a pending refresh at once, or create the file if missing."""
    with _timers_lock:
        pending = _timers.pop(pid, None)
    if pending:
        pending.cancel()
    if pending or not context.brief_path(pid).exists():
        generate(pid)


def _on_event(pid: str, topic: str, payload: Any) -> None:
    if pid and pid != "*":
        schedule(pid)


def watch() -> None:
    """Follow DAG and project-config changes (called once when the agents routes load)."""
    hooks.on_topic(("dag", "project"), _on_event)
